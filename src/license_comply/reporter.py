"""
Report generator for license-comply.

This module takes a ScanResult and produces output in one or more formats:
  - Terminal: Rich-formatted output with colors, tables, and panels
  - Markdown: A clean .md file using a Jinja2 template
  - HTML: A self-contained .html file with embedded CSS
  - JSON: Structured data for consumption by other tools

How it fits in the pipeline:
    scanner.py → resolver.py → classifier.py → analyzer.py → reporter.py

The terminal format is the default and uses the `rich` library for beautiful
output. The other formats generate files that can be shared or archived.
"""

from __future__ import annotations

import json
import os
from datetime import datetime

from jinja2 import Environment, FileSystemLoader, TemplateError
from rich.console import Console
from rich.panel import Panel
from rich.table import Table
from rich.text import Text

from license_comply.models import Finding, ObligationSummary, RiskLevel, ScanResult
from license_comply.utils import _TEMPLATES_DIR

# ---------------------------------------------------------------------------
# AI disclaimer — shown alongside any AI-generated content
# ---------------------------------------------------------------------------

_AI_DISCLAIMER = (
    "NOTE: This summary was generated by an AI language model. It is not legal "
    "advice and has not been reviewed by an attorney. Consult qualified legal "
    "counsel before making compliance decisions."
)

# ---------------------------------------------------------------------------
# Symbols and styles for terminal output
# ---------------------------------------------------------------------------

_RISK_SYMBOLS: dict[str, str] = {
    "clean": "[green]✓[/green]",
    "notice": "[blue]ℹ[/blue]",
    "warning": "[yellow]⚠[/yellow]",
    "critical": "[red]✗[/red]",
}

_RISK_COLORS: dict[str, str] = {
    "clean": "green",
    "notice": "blue",
    "warning": "yellow",
    "critical": "red",
}


