def _render_markdown(result: ScanResult, output_dir: str) -> str:
    """Render the scan result as a Markdown file.

    Args:
        result: The scan result.
        output_dir: Directory to save the file.

    Returns:
        The path to the generated Markdown file.
    """
    try:
        env = Environment(loader=FileSystemLoader(_TEMPLATES_DIR), autoescape=False)
        # Register a custom filter to escape pipe characters in markdown table
        # cells — an unescaped | would break the table layout.
        env.filters["escape_pipe"] = _escape_pipe
        template = env.get_template("report.md.jinja2")

        content = template.render(
            result=result,
            counts=_count_by_risk(result.findings),
            critical_findings=[f for f in result.findings if f.risk_level == RiskLevel.CRITICAL],
            warning_findings=[f for f in result.findings if f.risk_level == RiskLevel.WARNING],
            notice_findings=[f for f in result.findings if f.risk_level == RiskLevel.NOTICE],
            clean_findings=[f for f in result.findings if f.risk_level == RiskLevel.CLEAN],
            formatted_date=_format_timestamp(result.scan_timestamp),
        )
    except TemplateError as error:
        console = Console(stderr=True)
        console.print(f"[red]Error: Could not render Markdown report: {error}[/red]")
        console.print("  Hint: The Markdown template may be missing or corrupted.")
        console.print(f"  Expected location: {_TEMPLATES_DIR}")
        return ""

    filepath = os.path.join(output_dir, "license-comply-report.md")
    try:
        with open(filepath, "w", encoding="utf-8") as file:
            file.write(content)
    except OSError as error:
        console = Console(stderr=True)
        console.print(f"[red]Error: Could not write report to {filepath}: {error}[/red]")
        console.print("  Hint: Check that the output directory exists and is writable.")
        return ""

    return filepath


