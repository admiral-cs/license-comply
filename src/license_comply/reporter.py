def _escape_pipe(value: str) -> str:
    """Escape pipe characters for use in markdown table cells.

    An unescaped | in a markdown table cell would be interpreted as a column
    separator, breaking the table layout. This filter replaces | with \\|.

    Args:
        value: The string to escape.

    Returns:
        The string with | replaced by \\|.
    """
    if not isinstance(value, str):
        value = str(value)
    return value.replace("|", "\\|")


def _count_by_risk(findings: list[Finding]) -> dict[str, int]:
    """Count findings by risk level.

    Args:
        findings: The list of Finding objects from the analyzer.

    Returns:
        A dictionary mapping risk level names to counts.
    """
    counts: dict[str, int] = {"clean": 0, "notice": 0, "warning": 0, "critical": 0}
    for finding in findings:
        counts[finding.risk_level.value] = counts.get(finding.risk_level.value, 0) + 1
    return counts


def _risk_sort_key(risk_level: RiskLevel) -> int:
    """Sort key for risk levels: critical first, clean last.

    Args:
        risk_level: The RiskLevel enum value to sort.

    Returns:
        An integer sort key (lower = shown first in reports).
    """
    order = {
        RiskLevel.CRITICAL: 0,
        RiskLevel.WARNING: 1,
        RiskLevel.NOTICE: 2,
        RiskLevel.CLEAN: 3,
    }
    return order.get(risk_level, 99)


def _format_timestamp(raw_timestamp: str) -> str:
    """Convert an ISO 8601 timestamp to a human-readable date string.

    Takes a timestamp like "2026-02-25T14:30:00+00:00" and returns
    "February 25, 2026". Falls back to returning the raw string if
    parsing fails — so the template never breaks.

    Args:
        raw_timestamp: An ISO 8601 timestamp string.

    Returns:
        A formatted date like "February 25, 2026", or the raw string
        if parsing fails.
    """
    try:
        parsed = datetime.fromisoformat(raw_timestamp)
        return parsed.strftime("%B %d, %Y")
    except (ValueError, TypeError):
        return raw_timestamp


# Human-readable display names for obligation categories.
# These map from the short keys used in licenses.yaml to the labels shown
# in the HTML report's "By Obligation" tab.
_OBLIGATION_CATEGORY_LABELS: dict[str, str] = {
    "notice": "Notice & Attribution",
    "disclosure": "Modification Disclosure",
    "source_sharing": "Source Code Sharing",
    "use_restriction": "Use Restrictions",
    "technical": "Technical Requirements",
}

# Display order for obligation categories (most common → most serious).
_OBLIGATION_CATEGORY_ORDER: list[str] = [
    "notice",
    "disclosure",
    "source_sharing",
    "use_restriction",
    "technical",
]


def _build_obligations_by_license(
    obligation_rollup: list[ObligationSummary],
) -> list[dict]:
    """Regroup obligations by license instead of by obligation text.

    The existing obligation_rollup is grouped by obligation text:
        "Include copyright notice" → [requests (MIT), flask (BSD-3-Clause)]

    This helper inverts that into a list grouped by license:
        MIT → packages: [requests], obligations: ["Include copyright notice"]

    This grouping is more natural for reading in a legal report — you see
    each license, which packages use it, and what you must do.

    Args:
        obligation_rollup: The list of ObligationSummary objects from the
            analyzer.

    Returns:
        A list of dicts, each with keys: "license_id", "packages",
        "obligations". Sorted alphabetically by license_id.
    """
    # Build a mapping: license_id → {packages: set, obligations: list}
    license_map: dict[str, dict] = {}

    for obligation_summary in obligation_rollup:
        for package_name, license_id in zip(
            obligation_summary.packages, obligation_summary.license_ids
        ):
            if license_id not in license_map:
                license_map[license_id] = {"packages": set(), "obligations": []}

            license_map[license_id]["packages"].add(package_name)

            # Only add each obligation text once per license
            if obligation_summary.obligation not in license_map[license_id]["obligations"]:
                license_map[license_id]["obligations"].append(obligation_summary.obligation)

    # Convert to sorted list of dicts (sets → sorted lists for consistency)
    result = []
    for license_id in sorted(license_map.keys()):
        entry = license_map[license_id]
        result.append(
            {
                "license_id": license_id,
                "packages": sorted(entry["packages"]),
                "obligations": entry["obligations"],
            }
        )

    return result


def _build_obligations_by_package(
    obligation_rollup: list[ObligationSummary],
) -> list[dict]:
    """Regroup obligations by package instead of by obligation text.

    Produces a view like:
        requests (MIT) → ["Include copyright notice and license text"]
        chardet (LGPL-3.0-only) → ["Distribute modifications under LGPL", ...]

    This lets users quickly see "what do I need to do for THIS package?"

    Args:
        obligation_rollup: The list of ObligationSummary objects from the
            analyzer.

    Returns:
        A list of dicts, each with keys: "package_name", "license_id",
        "obligations". Sorted alphabetically by package_name.
    """
    # Build a mapping: package_name → {license_ids (set), obligations}
    package_map: dict[str, dict] = {}

    for obligation_summary in obligation_rollup:
        for package_name, license_id in zip(
            obligation_summary.packages, obligation_summary.license_ids
        ):
            if package_name not in package_map:
                package_map[package_name] = {"license_ids": set(), "obligations": []}

            # Track all license IDs associated with this package
            package_map[package_name]["license_ids"].add(license_id)

            # Only add each obligation text once per package
            if obligation_summary.obligation not in package_map[package_name]["obligations"]:
                package_map[package_name]["obligations"].append(obligation_summary.obligation)

    # Convert to sorted list of dicts for the template.
    # Join multiple license IDs with " + " for display (e.g., "MIT + GPL-3.0-only").
    result = []
    for package_name in sorted(package_map.keys()):
        entry = package_map[package_name]
        result.append(
            {
                "package_name": package_name,
                "license_id": " + ".join(sorted(entry["license_ids"])),
                "obligations": entry["obligations"],
            }
        )

    return result


def _build_obligations_by_category(
    obligation_rollup: list[ObligationSummary],
) -> list[dict]:
    """Group obligations by their category for a more readable view.

    Instead of a flat list of obligations, this produces groups like:
        Notice & Attribution:
            - Include copyright notice (required by: requests, flask)
        Source Code Sharing:
            - Distribute source under GPL (required by: gpl-pkg)

    This makes it much easier to scan for specific types of obligations
    than reading through an unsorted flat list.

    Args:
        obligation_rollup: The list of ObligationSummary objects from the
            analyzer.

    Returns:
        A list of dicts, each with keys: "category_key", "category_label",
        "obligations". Each obligation is a dict with "text", "packages",
        "license_ids". Ordered by _OBLIGATION_CATEGORY_ORDER.
    """
    # Build a mapping: category_key → list of obligation dicts
    category_map: dict[str, list[dict]] = {}

    for obligation_summary in obligation_rollup:
        category_key = obligation_summary.category or "notice"

        if category_key not in category_map:
            category_map[category_key] = []

        category_map[category_key].append(
            {
                "text": obligation_summary.obligation,
                "packages": obligation_summary.packages,
                "license_ids": obligation_summary.license_ids,
            }
        )

    # Convert to ordered list following _OBLIGATION_CATEGORY_ORDER
    result = []
    for category_key in _OBLIGATION_CATEGORY_ORDER:
        if category_key in category_map:
            result.append(
                {
                    "category_key": category_key,
                    "category_label": _OBLIGATION_CATEGORY_LABELS.get(
                        category_key, category_key.replace("_", " ").title()
                    ),
                    "obligations": category_map[category_key],
                }
            )

    # Include any categories not in the predefined order (future-proofing)
    for category_key in sorted(category_map.keys()):
        if category_key not in _OBLIGATION_CATEGORY_ORDER:
            result.append(
                {
                    "category_key": category_key,
                    "category_label": _OBLIGATION_CATEGORY_LABELS.get(
                        category_key, category_key.replace("_", " ").title()
                    ),
                    "obligations": category_map[category_key],
                }
            )

    return result
