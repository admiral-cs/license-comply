def _render_json(result: ScanResult, output_dir: str) -> str:
    """Render the scan result as a JSON file.

    Args:
        result: The scan result.
        output_dir: Directory to save the file.

    Returns:
        The path to the generated JSON file.
    """
    data = _scan_result_to_dict(result)

    filepath = os.path.join(output_dir, "license-comply-report.json")
    try:
        with open(filepath, "w", encoding="utf-8") as file:
            json.dump(data, file, indent=2, sort_keys=False)
    except OSError as error:
        console = Console(stderr=True)
        console.print(f"[red]Error: Could not write report to {filepath}: {error}[/red]")
        console.print("  Hint: Check that the output directory exists and is writable.")
        return ""

    return filepath


def _scan_result_to_dict(result: ScanResult) -> dict:
    """Convert a ScanResult to a plain dictionary for JSON serialization."""
    return {
        "project_path": result.project_path,
        "project_type": result.project_type.value,
        "total_packages": result.total_packages,
        "direct_count": result.direct_count,
        "transitive_count": result.transitive_count,
        "scan_timestamp": result.scan_timestamp,
        "tool_version": result.tool_version,
        "ai_summary": result.ai_summary,
        "ai_summary_disclaimer": _AI_DISCLAIMER if result.ai_summary else None,
        "findings": [
            {
                "package_name": f.package_name,
                "declared_license": f.license_info.declared_license,
                "spdx_id": f.license_info.spdx_id,
                "category": f.license_info.category.value,
                "risk_level": f.risk_level.value,
                "is_transitive": f.license_info.is_transitive,
                "title": f.title,
                "explanation": f.explanation,
                "recommendation": f.recommendation,
                "remediation_steps": f.remediation_steps,
                "policy_violated": f.policy_violated,
                "classification_note": f.license_info.classification_note,
                "pypi_url": f.license_info.pypi_url,
                "source_url": f.license_info.source_url,
            }
            for f in result.findings
        ],
        "obligation_rollup": [
            {
                "obligation": o.obligation,
                "packages": o.packages,
                "license_ids": o.license_ids,
            }
            for o in result.obligation_rollup
        ],
    }


