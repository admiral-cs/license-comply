# Public API
# ---------------------------------------------------------------------------


def generate_report(
    result: ScanResult,
    formats: list[str],
    output_dir: str = ".",
    ci_mode: bool = False,
) -> list[str]:
    """Generate reports in one or more formats.

    Args:
        result: The complete scan result from the analyzer.
        formats: List of format strings (e.g., ["terminal", "markdown"]).
        output_dir: Directory to save file-based reports.
        ci_mode: If True, suppress decorative terminal output.

    Returns:
        A list of file paths for any generated report files.
        Terminal output is printed directly and not included in the list.
    """
    # Ensure the output directory exists — prevents FileNotFoundError when
    # saving report files to a directory that hasn't been created yet.
    # exist_ok=True means it silently succeeds if the directory already exists.
    if output_dir != ".":
        os.makedirs(output_dir, exist_ok=True)

    generated_files: list[str] = []

    for fmt in formats:
        if fmt == "terminal":
            _render_terminal(result, ci_mode=ci_mode)
        elif fmt == "markdown":
            filepath = _render_markdown(result, output_dir)
            if filepath:
                generated_files.append(filepath)
        elif fmt == "html":
            filepath = _render_html(result, output_dir)
            if filepath:
                generated_files.append(filepath)
        elif fmt == "json":
            filepath = _render_json(result, output_dir)
            if filepath:
                generated_files.append(filepath)

    return generated_files


