def _render_terminal(result: ScanResult, ci_mode: bool = False) -> None:
    """Render the scan result to the terminal using Rich.

    Args:
        result: The scan result to display.
        ci_mode: If True, use plain text without colors.
    """
    if ci_mode:
        # no_color disables color codes; omitting force_terminal lets Rich
        # auto-detect that stdout is piped (not a TTY) in CI, so it skips
        # ALL ANSI escape codes — including bold/italic — producing plain text.
        console = Console(no_color=True)
    else:
        console = Console()

    # Count findings by risk level
    counts = _count_by_risk(result.findings)

    # --- Header ---
    console.print()
    console.print(f"[bold]license-comply v{result.tool_version}[/bold]")
    console.print(f"Scanning: {result.project_path}")
    console.print(f"Project type: {result.project_type.value}")
    console.print()

    # --- AI Summary (if present) ---
    if result.ai_summary:
        console.print(Panel(result.ai_summary, title="AI Executive Summary", border_style="blue"))
        console.print(f"\n[dim italic]{_AI_DISCLAIMER}[/dim italic]")
        console.print()

    # --- Summary ---
    console.print("[bold]" + "=" * 40 + "[/bold]")
    console.print("[bold]RESULTS SUMMARY[/bold]")
    console.print("[bold]" + "=" * 40 + "[/bold]")
    console.print(f"Total packages:  {result.total_packages}")
    if result.transitive_count > 0:
        console.print(f"  Direct: {result.direct_count} / Transitive: {result.transitive_count}")
    console.print(f"[green]Clean:           {counts.get('clean', 0)}[/green]")
    console.print(f"[blue]Notice:          {counts.get('notice', 0)}[/blue]")
    console.print(f"[yellow]Warnings:        {counts.get('warning', 0)}[/yellow]")
    console.print(f"[red]Critical:        {counts.get('critical', 0)}[/red]")
    console.print()

    # --- Dependency table ---
    table = Table(title="Dependencies", show_lines=True)
    table.add_column("Package", style="bold")
    table.add_column("License")
    table.add_column("Category")
    table.add_column("Risk", justify="center")

    # Sort: critical first, then warning, notice, clean
    sorted_findings = sorted(result.findings, key=lambda f: _risk_sort_key(f.risk_level))

    for finding in sorted_findings:
        risk_symbol = _RISK_SYMBOLS.get(finding.risk_level.value, "?")
        license_str = (
            finding.license_info.spdx_id or finding.license_info.declared_license or "Unknown"
        )
        category_str = finding.license_info.category.value.replace("_", " ").title()

        # Add a dim "(transitive)" tag after transitive package names
        package_display = finding.package_name
        if finding.license_info.is_transitive:
            package_display = Text.from_markup(f"{finding.package_name} [dim](transitive)[/dim]")

        table.add_row(
            package_display,
            license_str,
            category_str,
            Text.from_markup(f"{risk_symbol} {finding.risk_level.value.upper()}"),
        )

    console.print(table)
    console.print()

    # --- Critical findings ---
    critical_findings = [f for f in result.findings if f.risk_level == RiskLevel.CRITICAL]
    if critical_findings:
        console.print("[bold]" + "=" * 40 + "[/bold]")
        console.print("[bold red]CRITICAL ISSUES[/bold red]")
        console.print("[bold]" + "=" * 40 + "[/bold]")
        console.print()
        for finding in critical_findings:
            _print_finding(console, finding)

    # --- Warnings ---
    warning_findings = [f for f in result.findings if f.risk_level == RiskLevel.WARNING]
    if warning_findings:
        console.print("[bold]" + "=" * 40 + "[/bold]")
        console.print("[bold yellow]WARNINGS[/bold yellow]")
        console.print("[bold]" + "=" * 40 + "[/bold]")
        console.print()
        for finding in warning_findings:
            _print_finding(console, finding)

    # --- Obligation rollup ---
    if result.obligation_rollup:
        console.print("[bold]" + "=" * 40 + "[/bold]")
        console.print("[bold]YOUR OBLIGATIONS[/bold]")
        console.print("[bold]" + "=" * 40 + "[/bold]")
        console.print()
        for obligation in result.obligation_rollup:
            packages_str = ", ".join(
                f"{pkg} ({lid})" for pkg, lid in zip(obligation.packages, obligation.license_ids)
            )
            console.print(f"  • {obligation.obligation}")
            console.print(f"    Required by: {packages_str}")
            console.print()

    # Print legal disclaimer at the end of the report
    console.print("[dim]This report does not constitute legal advice.[/dim]")


def _print_finding(console: Console, finding: Finding) -> None:
    """Print a single finding with its details to the terminal.

    Args:
        console: The Rich Console instance for output.
        finding: The Finding object to display.
    """
    risk_symbol = _RISK_SYMBOLS.get(finding.risk_level.value, "?")
    license_str = finding.license_info.spdx_id or "UNKNOWN"
    color = _RISK_COLORS.get(finding.risk_level.value, "white")

    # Add a dim "(transitive)" tag after transitive package names in findings
    transitive_tag = " [dim](transitive)[/dim]" if finding.license_info.is_transitive else ""
    console.print(
        f"{risk_symbol} [bold]{finding.package_name}[/bold]{transitive_tag} ({license_str})"
    )
    risk_label = finding.risk_level.value.upper()
    console.print(f"  Risk: [{color}]{risk_label}[/{color}] — {finding.title}")
    console.print(f"  {finding.explanation}")
    console.print(f"  [bold]Action:[/bold] {finding.recommendation}")
    if finding.remediation_steps:
        console.print("  [bold]Next steps:[/bold]")
        for i, step in enumerate(finding.remediation_steps, start=1):
            console.print(f"    {i}. {step}")
    if finding.policy_violated:
        console.print(f"  [dim]Policy: {finding.policy_violated}[/dim]")
    console.print()


